"""Regenerate scripts/recap_tw.py: the Traditional Chinese (Taiwan) recap texts, converted from the Simplified ones in
recap_text.py with OpenCC (s2twp: Taiwan phrasing). Run after changing a ZH template:

    pip install opencc-python-reimplemented==0.1.7 && python3 scripts/make_recap_tw.py

The daily build only reads the generated file, so it needs no OpenCC.
"""
import importlib.util, os, pprint
from opencc import OpenCC

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "recap_tw.py")
if os.path.exists(OUT): os.remove(OUT)   # convert from the Simplified texts, not from an earlier conversion
spec = importlib.util.spec_from_file_location("recap_text", os.path.join(HERE, "recap_text.py"))
rt = importlib.util.module_from_spec(spec); spec.loader.exec_module(rt)
cc = OpenCC("s2twp")
FIX = {"覆盤": "復盤"}   # OpenCC slips on these
def tw(x):
    x = cc.convert(x)
    for a, b in FIX.items(): x = x.replace(a, b)
    return x
conv = lambda v: tw(v) if isinstance(v, str) else [conv(x) for x in v] if isinstance(v, list) else {k: conv(x) for k, x in v.items()} if isinstance(v, dict) else v
data = {"TPL": conv(rt.ZH), "NAMES": conv(rt.NAMES["zh"]), "UI": conv(rt.UI["zh"]), "WD": conv(rt.WD["zh"])}
with open(OUT, "w", encoding="utf-8") as f:
    f.write('"""Generated by scripts/make_recap_tw.py from the Simplified texts in recap_text.py (OpenCC s2twp). Do not edit by hand."""\n')
    for k, v in data.items():
        f.write(f"{k} = " + pprint.pformat(v, width=160, sort_dicts=False) + "\n")
print("wrote", OUT)
